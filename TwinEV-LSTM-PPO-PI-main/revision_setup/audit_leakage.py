"""Audit forecast alignment, splits, scaling, and PPO forecast provenance."""

from __future__ import annotations

import ast
import argparse
from pathlib import Path

import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[1]


def source(path: str) -> str:
    return (ROOT / path).read_text(encoding="utf-8")


def check(name: str, condition: bool, evidence: str, report: list[str]) -> None:
    status = "PASS" if condition else "FAIL"
    report.append(f"- **{status}** — {name}: `{evidence}`")
    assert condition, f"{name} failed: {evidence}"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--forecast-csv", type=Path, default=ROOT / "acn_target_a_bilstm_full.csv")
    parser.add_argument("--output", type=Path, default=Path(__file__).parent / "audit_report.md")
    args = parser.parse_args()

    build = source("build_demand_forecaster.py")
    alternative = source("test_alternative_targets.py")
    generator = source("generate_forecast_feature.py")
    runner = source("exp_2x2_run.py")
    controller = source("train_controller.py")
    report = ["# Forecast and PPO leakage audit", "", "Generated by `revision_setup/audit_leakage.py`.", ""]

    check(
        "Target is the next six hours",
        "sum(demand[t+1 .. t+horizon])" in alternative
        and "rolling(horizon).sum().shift(-horizon)" in alternative,
        "test_alternative_targets.py:75-80",
        report,
    )
    check(
        "Sequence target follows the input sequence",
        "X.append(arr[i:i + seq_len])" in build
        and "y.append(arr[i + seq_len, 0])" in build,
        "build_demand_forecaster.py:126-131",
        report,
    )
    check(
        "Input features exclude the forward target",
        "input_cols = LAG_FEATURE_COLS + CALENDAR_COLS" in generator
        and 'feat_df[["target"]]' in generator,
        "generate_forecast_feature.py:113-119",
        report,
    )
    check(
        "Input scaler is fit on training rows only",
        "input_scaler.fit(feat_df[input_cols].iloc[:f_train_end])" in generator,
        "generate_forecast_feature.py:114-118",
        report,
    )
    check(
        "Target scaler is fit on training rows only",
        'target_scaler.fit(feat_df[["target"]].iloc[:f_train_end])' in generator,
        "generate_forecast_feature.py:116-119",
        report,
    )
    check(
        "Chronological 70/15/15 split is implemented",
        "train_end = int(n * 0.70)" in build
        and "val_end = int(n * 0.85)" in build
        and "train_end = int(n_steps * 0.70)" in controller
        and "val_end = int(n_steps * 0.85)" in controller,
        "build_demand_forecaster.py:211-219; train_controller.py:84-87",
        report,
    )
    check(
        "PPO test observations use predicted forecasts",
        '"predicted"' in controller and "self._by_time" in controller,
        "train_controller.py:102-130",
        report,
    )
    check(
        "PPO test actions are deterministic",
        "model.predict(obs, deterministic=True)" in runner,
        "exp_2x2_run.py:274-276",
        report,
    )
    check(
        "Forecast-safe test range begins at validation boundary",
        "test_lo = val_end" in runner and "test_range" in runner,
        "exp_2x2_run.py:117-127",
        report,
    )
    check(
        "Forecast training rows are in-sample",
        "Predict on EVERY sequence (train+val+test)" in generator
        and "IN-SAMPLE" in generator,
        "generate_forecast_feature.py:137-189",
        report,
    )

    forecast = pd.read_csv(args.forecast_csv)
    required = {"hour_index", "timestamp", "predicted", "input_last_index"}
    check(
        "Forecast file contains alignment metadata",
        required.issubset(forecast.columns),
        f"{args.forecast_csv}: required columns",
        report,
    )
    if required.issubset(forecast.columns):
        check(
            "Forecast input cutoff is before prediction index",
            bool((forecast["input_last_index"] == forecast["hour_index"] - 1).all()),
            "input_last_index == hour_index - 1",
            report,
        )
        check(
            "Forecast timestamps are unique and ordered",
            bool(forecast["timestamp"].is_unique and forecast["timestamp"].is_monotonic_increasing),
            "timestamp uniqueness/order",
            report,
        )
        check(
            "Forecast predictions are finite",
            bool(np.isfinite(forecast["predicted"].to_numpy(dtype=float)).all()),
            "predicted finite",
            report,
        )

    report.extend(
        [
            "",
            "## Required follow-up",
            "",
            "Training and validation forecast rows are in-sample model outputs. "
            "They do not contaminate the held-out test metric, but they are not "
            "deployment-realistic PPO observations. `oof_forecast.py` is provided "
            "to generate blocked, expanding-fold training forecasts without "
            "overwriting the existing forecast file.",
            "",
            "The generated forecast uses a one-grid-step-earlier input cutoff "
            "(`input_last_index = hour_index - 1`). This is conservative rather "
            "than future-leaking and should be stated explicitly.",
        ]
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(report) + "\n", encoding="utf-8")
    print(args.output)


if __name__ == "__main__":
    main()
